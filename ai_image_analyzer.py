@dataclass
class TestResult:
    """Result of a single forensic test.

    ``score`` is the AI probability in **percent** (0–100):
      0  = certainly a real photograph
      50 = uncertain / mixed signals
      100 = certainly AI-generated
    """
    name: str
    score: float                       # 0–100 AI probability
    confidence: float                  # 0.0–1.0
    explanation: str = ""
    details: dict[str, Any] = field(default_factory=dict)

    @property
    def real_confidence(self) -> float:
        """Confidence that the image is a real photograph (100 − AI%)."""
        return max(0.0, 100.0 - self.score)

    @property
    def verdict(self) -> str:
        if self.score > AI_THRESHOLD:
            return "AI-Generated"
        elif self.score < UNCERTAIN_LOW:
            return "Real Camera"
        return "Uncertain"


@dataclass
class AnalysisReport:
    """Full analysis report combining all test results."""
    image_path: str
    image_size: tuple[int, int]
    file_size: int
    timestamp: str
    tests: list[TestResult]
    overall_score: float = 0.0          # 0–100 AI probability
    overall_confidence: float = 0.0     # 0.0–1.0
    verdict: str = "Uncertain"
    summary: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "image_path": self.image_path,
            "image_size": self.image_size,
            "file_size": self.file_size,
            "timestamp": self.timestamp,
            "verdict": self.verdict,
            "ai_probability": round(self.overall_score, 2),
            "real_probability": round(max(0.0, 100.0 - self.overall_score), 2),
            "confidence": round(self.overall_confidence, 4),
            "summary": self.summary,
            "tests": [
                {
                    "name": t.name,
                    "ai_probability": round(t.score, 2),
                    "real_probability": round(max(0.0, 100.0 - t.score), 2),
                    "confidence": round(t.confidence, 4),
                    "verdict": t.verdict,
                    "explanation": t.explanation,
                    "details": _json_safe(t.details),
                }
                for t in self.tests
            ],
        }


