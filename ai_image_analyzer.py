#  Test 4 — Statistical Analysis
# ════════════════════════════════════════════════════════════════════════════

def test_statistics(cv_img: np.ndarray) -> TestResult:
    """
    Statistical tests on pixel-level distributions.

    Recalibrated v2:
      • Channel correlation 0.90–0.98 is **normal** for real photos
        (only > 0.98 is suspicious)
      • JPEG compression naturally reduces entropy — not anomalous
      • Double-JPEG is common (social media re-encodes) — reduced penalty
    """
    findings: list[str] = []
    details: dict[str, Any] = {}
    ai_prob = 50.0
    confidence = 0.5

    gray = cv2.cvtColor(cv_img, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape
    total_pixels = h * w

    # --- Histogram entropy ---
    hist, _ = np.histogram(gray.flatten(), bins=256, range=(0, 255))
    hist_norm = hist / (total_pixels + 1e-12)
    hist_norm = hist_norm[hist_norm > 0]
    entropy = float(-np.sum(hist_norm * np.log2(hist_norm)))
    max_entropy = 8.0
    normalized_entropy = entropy / max_entropy

    details["histogram_entropy"] = round(entropy, 4)
    details["normalized_entropy"] = round(normalized_entropy, 4)

    if normalized_entropy < 0.50:
        findings.append(
            f"Very low histogram entropy ({normalized_entropy:.2%}). "
            f"May indicate posterisation from AI or heavy compression."
        )
        ai_prob = min(80.0, ai_prob + 15.0)
        confidence = max(confidence, 0.5)
    elif normalized_entropy < 0.65:
        findings.append(f"Low-ish entropy ({normalized_entropy:.2%}) — could be JPEG compression, not necessarily AI.")
        ai_prob = ai_prob + 5.0
        confidence = max(confidence, 0.3)
    else:
        findings.append(f"Histogram entropy ({normalized_entropy:.2%}) is healthy (neutral signal).")
        # High entropy is neutral — both real photos and AI images can have high entropy
        confidence = max(confidence, 0.2)

    # --- Channel correlation ---
    b, g, r = cv2.split(cv_img)
    b_flat = b.astype(np.float64).flatten()
    g_flat = g.astype(np.float64).flatten()
    r_flat = r.astype(np.float64).flatten()

    bg_corr = float(np.corrcoef(b_flat, g_flat)[0, 1])
    br_corr = float(np.corrcoef(b_flat, r_flat)[0, 1])
    gr_corr = float(np.corrcoef(g_flat, r_flat)[0, 1])
    avg_channel_corr = (abs(bg_corr) + abs(br_corr) + abs(gr_corr)) / 3.0

    details["channel_correlation"] = round(avg_channel_corr, 4)
    details["channel_correlations"] = {
        "B-G": round(bg_corr, 4), "B-R": round(br_corr, 4), "G-R": round(gr_corr, 4),
    }

    if avg_channel_corr > 0.99:
        findings.append(
            f"Extremely high inter-channel correlation (r={avg_channel_corr:.4f}). "
            f"This is unusually high and can indicate AI synthesis."
        )
        ai_prob = min(95.0, ai_prob + 25.0)
        confidence = max(confidence, 0.7)
    elif avg_channel_corr > 0.97:
        findings.append(f"Very high channel correlation (r={avg_channel_corr:.4f}), moderately suspicious.")
        ai_prob = min(95.0, ai_prob + 10.0)
        confidence = max(confidence, 0.5)
    elif avg_channel_corr > 0.95:
        findings.append(f"Channel correlation ({avg_channel_corr:.4f}) is on the high side.")
        ai_prob = ai_prob + 3.0
        confidence = max(confidence, 0.3)
    else:
        findings.append(f"Channel correlation ({avg_channel_corr:.4f}) is normal for real photographs.")
        ai_prob = max(15.0, ai_prob - 10.0)
        confidence = max(confidence, 0.4)

    # --- Kurtosis ---
    gray_flat = gray.astype(np.float64).flatten()
    kurt = float(((gray_flat - np.mean(gray_flat)) ** 4).mean() / (np.var(gray_flat) ** 2 + 1e-12))
    excess_kurtosis = kurt - 3.0
    details["excess_kurtosis"] = round(excess_kurtosis, 4)

    if excess_kurtosis > 6.0:
        findings.append(
            f"High excess kurtosis ({excess_kurtosis:.2f}). "
            f"Pixel distribution has very heavy tails."
        )
        ai_prob = min(95.0, ai_prob + 10.0)
        confidence = max(confidence, 0.45)

    # --- Double JPEG ---
    double_jpeg_score = _check_double_jpeg(gray)
    details["double_jpeg"] = round(double_jpeg_score, 4)

    if double_jpeg_score > 0.9:
        findings.append("Strong double-JPEG compression detected (common with re-saved images).")
        ai_prob = min(95.0, ai_prob + 2.0)
        confidence = max(confidence, 0.20)

    explanation = "; ".join(findings)
    return TestResult(
        name="Statistical Analysis",
        score=ai_prob,
        confidence=confidence,
        explanation=explanation,
        details=details,
    )


def _check_double_jpeg(gray: np.ndarray) -> float:
    """Detect double JPEG compression via 8x8 block boundary analysis."""
    try:
        h, w = gray.shape
        if h < 128 or w < 128:
            return 0.0

        block_size = 8
        diff_h = np.abs(np.diff(gray[::block_size, :].astype(np.float64), axis=0))
        diff_v = np.abs(np.diff(gray[:, ::block_size].astype(np.float64), axis=1))

        block_boundary_strength = float(np.mean(diff_h) + np.mean(diff_v)) / 2.0
        global_gradient = float(np.mean(np.abs(np.diff(gray.astype(np.float64)))))
        if global_gradient < 1e-8:
            return 0.0

        return min(1.0, block_boundary_strength / global_gradient)
    except Exception:
        return 0.0


