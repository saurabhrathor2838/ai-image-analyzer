def print_batch_summary(reports: list[AnalysisReport], no_color: bool = False,
                        threshold: float = 0.65) -> None:
    """Print a summary table of batch analysis results."""
    if not reports:
        print("No images found to analyse.")
        return

    sorted_reports = sorted(reports, key=lambda r: r.overall_score, reverse=True)

    name_w = min(55, max(len("File"), max(len(os.path.basename(r.image_path)) for r in sorted_reports) + 2))
    ai_w = 10
    real_w = 10
    verdict_w = 24

    print()
    print("=" * (name_w + ai_w + real_w + verdict_w + 8))
