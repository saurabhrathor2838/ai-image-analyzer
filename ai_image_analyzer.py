#  Test 5 — Visual Artifact Detection
# ════════════════════════════════════════════════════════════════════════════

def test_artifacts(cv_img: np.ndarray) -> TestResult:
    """
    Look for visual artefacts common in AI-generated images.

    Recalibrated v2:
      • Smooth portraits / HDR photos are **not** suspicious
      • Only flag *extreme* over-smoothing with *additional* AI signals
      • Natural textures (fabric, skin, foliage) are rewarded as REAL
    """
    findings: list[str] = []
    details: dict[str, Any] = {}
    ai_prob = 50.0
    confidence = 0.5

    gray = cv2.cvtColor(cv_img, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape

    # --- High-frequency detail ---
    blurred = cv2.GaussianBlur(gray, (5, 5), 0)
    hf_content = gray.astype(np.float64) - blurred.astype(np.float64)
    hf_energy = float(np.sum(hf_content ** 2))
    total_energy = float(np.sum(gray.astype(np.float64) ** 2)) + 1e-12
    hf_ratio = hf_energy / total_energy
    details["high_freq_detail_ratio"] = round(hf_ratio, 6)

    if hf_ratio < 0.0005:
        findings.append(
            f"Very low high-frequency detail ({hf_ratio:.4%}). "
            f"Image appears significantly over-smoothed — common in AI output."
        )
        ai_prob = min(95.0, ai_prob + 25.0)
        confidence = max(confidence, 0.7)
    elif hf_ratio < 0.002:
        findings.append(f"Low high-frequency detail ({hf_ratio:.4%}), somewhat over-smoothed.")
        ai_prob = min(95.0, ai_prob + 8.0)
        confidence = max(confidence, 0.4)
    else:
        findings.append(f"Normal high-frequency detail ({hf_ratio:.4%}), consistent with textural variation in real photos.")
        ai_prob = max(10.0, ai_prob - 20.0)
        confidence = max(confidence, 0.6)

    # --- Symmetry ---
    left_half = gray[:, :w // 2]
    right_half = gray[:, w - w // 2:][:, ::-1]
    min_w = min(left_half.shape[1], right_half.shape[1])
    symmetry_score = float(np.mean(np.abs(
        left_half[:, :min_w].astype(np.float64) - right_half[:, :min_w].astype(np.float64)
    )))
    max_val = float(max(np.max(left_half), np.max(right_half), 1))
    normalized_symmetry = symmetry_score / (max_val + 1e-8)
    details["symmetry_score"] = round(normalized_symmetry, 4)

    # Only flag symmetry when combined with low detail (both = strong AI signal)
    if normalized_symmetry < 0.10 and hf_ratio < 0.002:
        findings.append(
            f"High symmetry (score={normalized_symmetry:.3f}) combined with low detail "
            f"— characteristic of AI generation."
        )
        ai_prob = min(95.0, ai_prob + 18.0)
        confidence = max(confidence, 0.55)

    # --- Edge density ---
    edges = cv2.Canny(gray, 50, 150)
    edge_density = float(np.sum(edges > 0)) / (h * w)
    details["edge_density"] = round(edge_density, 4)

    if edge_density < 0.01:
        findings.append(f"Very low edge density ({edge_density:.2%}). AI images often lack fine detail.")
        ai_prob = min(95.0, ai_prob + 10.0)
        confidence = max(confidence, 0.45)
    elif edge_density > 0.25:
        findings.append(f"High edge density ({edge_density:.2%}) could indicate over-sharpening.")
        ai_prob = min(95.0, ai_prob + 4.0)
        confidence = max(confidence, 0.30)
    else:
        findings.append(f"Edge density ({edge_density:.2%}) is within normal bounds for photographs.")
        ai_prob = max(15.0, ai_prob - 8.0)
        confidence = max(confidence, 0.4)

    # --- Texture variance ---
    texture_variance = _texture_analysis(gray)
    details["texture_variance"] = round(texture_variance, 4)

    if texture_variance < 200.0:
        findings.append(
            f"Low texture variance ({texture_variance:.1f}). "
            f"Image lacks micro-texture detail typical of real photographs."
        )
        ai_prob = min(95.0, ai_prob + 15.0)
        confidence = max(confidence, 0.5)
    elif texture_variance > 2000.0:
        findings.append(f"Healthy texture variance ({texture_variance:.1f}), consistent with real photographic detail.")
        ai_prob = max(10.0, ai_prob - 15.0)
        confidence = max(confidence, 0.6)
    else:
        findings.append(f"Texture variance ({texture_variance:.1f}) is moderate.")
        ai_prob = max(15.0, ai_prob - 3.0)

    # --- Text & Grid Anomaly Detection ---
    anomaly_score, anomaly_details = _detect_text_grid_anomalies(cv_img)
    details.update(anomaly_details)

    if anomaly_score > 0:
        if anomaly_score >= 40:
            findings.append(
                f"Strong text/grid anomalies detected ({anomaly_score:.0f} pts): "
                f"large smooth white background with hyper-uniform texture "
                f"and periodic patterns — characteristic of AI-generated "
                f"notebook pages, diagrams, or text renders."
            )
            ai_prob = min(95.0, ai_prob + int(anomaly_score))
            confidence = max(confidence, 0.8)
        elif anomaly_score >= 15:
            findings.append(
                f"Mild text/grid anomalies detected ({anomaly_score:.0f} pts): "
                f"smooth backgrounds and mild periodicity — common in "
                f"synthetic text/diagrams."
            )
            ai_prob = min(95.0, ai_prob + int(anomaly_score * 0.7))
            confidence = max(confidence, 0.6)

    explanation = "; ".join(findings)
    return TestResult(
        name="Visual Artifact Detection",
        score=ai_prob,
        confidence=confidence,
        explanation=explanation,
        details=details,
    )


def _texture_analysis(gray: np.ndarray) -> float:
    """Quick texture analysis using local variance of the Laplacian."""
    try:
        lap = cv2.Laplacian(gray, cv2.CV_64F)
        h, w = lap.shape
        step = 32
        variances = []
        for i in range(0, h - step, step):
            for j in range(0, w - step, step):
                block = lap[i:i + step, j:j + step]
                variances.append(float(np.var(block)))
        return float(np.mean(variances)) if variances else 0.0
    except Exception:
        return 0.0


# ════════════════════════════════════════════════════════════════════════════
#  Scoring Engine
# ════════════════════════════════════════════════════════════════════════════

def _sigmoid_scale(score: float, steepness: float = 0.08) -> float:
    """Apply a sigmoid (logistic) scaling curve to push extreme scores
    toward 0 or 100.

    50 maps to 50 (neutral).  Values far from 50 are amplified:
        0%  → ~1.8%
       20%  → ~8.0%
       30%  → ~15%
       40%  → ~23%
       50%  → 50%
       60%  → ~77%
       70%  → ~85%
       80%  → ~92%
       100% → ~98.2%
    """
    return max(0.0, min(100.0, 100.0 / (1.0 + math.exp(-steepness * (score - 50.0)))))


def _expand_test_score(score: float, confidence: float) -> float:
    """Expand a test's score away from 50% based on its confidence.

    High-confidence tests are pushed toward 0 or 100, making them
    more decisive in the aggregate.  Low-confidence tests stay near 50.
    """
    factor = 0.5 + confidence  # range 0.5 – 1.5
    return max(0.0, min(100.0, 50.0 + (score - 50.0) * factor))


def _determine_has_exif(tests: list[TestResult]) -> bool:
    """Check whether any metadata test found real EXIF data."""
    for t in tests:
        if t.name.lower().split()[0] in ("metadata", "c2pa"):
            exif_tag_count = t.details.get("exif_tag_count", 0)
            if exif_tag_count and exif_tag_count > 0:
                return True
            # Metadata test stores rich exif in its details
            exif_data = t.details.get("exif")
            if exif_data and len(exif_data) > 0:
                return True
    return False


def aggregate_results(
    tests: list[TestResult],
    threshold: float = 0.55,
    has_exif: bool = True,
) -> tuple[float, float, str, str]:
    """
    Combine all test results into an overall AI-probability score.

    Pipeline (v3.0):
      1. **Dynamic weighting** — if EXIF is absent, boost physical-signal
         tests (Noise, Frequency, Visual) and reduce metadata weights.
      2. **Score expansion** — each test's score is expanded away from 50
         proportionally to its confidence.
      3. **Weighted aggregation** — confidence-weighted average of
         expanded scores.
      4. **Sigmoid scaling** — final non-linear transform for stronger
         verdict confidence (extreme signals → closer to 0 / 100).
    """
    # ── 1. Dynamic weight adjustment ───────────────────────────────────
    if not has_exif:
        # Boost physical signal tests, reduce metadata tests
        weight_multipliers = DYNAMIC_WEIGHTS_NO_EXIF
    else:
        weight_multipliers = {k: 1.0 for k in TEST_WEIGHTS}

    # ── 2. Per-test score expansion ──────────────────────────────────────
    weighted_sum = 0.0
    weight_total = 0.0
    confidence_values: list[float] = []

    for test in tests:
        key = test.name.lower().split()[0]
        base_weight = TEST_WEIGHTS.get(key, 0.2)
        multiplier = weight_multipliers.get(key, 1.0)
        weight = base_weight * multiplier

        expanded_score = _expand_test_score(test.score, test.confidence)
        weighted_sum += expanded_score * weight * test.confidence
        weight_total += weight * test.confidence
        confidence_values.append(test.confidence)

    raw_score = weighted_sum / (weight_total + 1e-12) if weight_total > 0 else 50.0
    overall_confidence = float(np.mean(confidence_values))

    # ── 3 & 4. Non-linear sigmoid scaling on the aggregated score ──────
    overall_score = _sigmoid_scale(raw_score)

    # ── Verdict ────────────────────────────────────────────────────────
    if overall_score < UNCERTAIN_LOW:
        verdict = "Real Camera Photo"
    elif overall_score <= AI_THRESHOLD:
        verdict = "Uncertain / Mixed Signals"
    else:
        verdict = "AI-Generated"

    ai_tests = [t for t in tests if t.score > 50.0]
    real_tests = [t for t in tests if t.score < 50.0]

    parts = [
        f"AI Probability: {overall_score:.0f}% (Real: {100 - overall_score:.0f}%) (conf: {overall_confidence:.0%})",
    ]
    if ai_tests:
        parts.append(f"AI indicators from: {', '.join(t.name for t in ai_tests)}")
    if real_tests:
        parts.append(f"Real-photo indicators from: {', '.join(t.name for t in real_tests)}")
    parts.append(f"Verdict: {verdict}")

    summary = " | ".join(parts)

    return overall_score, overall_confidence, verdict, summary


