IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".bmp", ".webp", ".gif", ".tiff", ".tif"}


def find_images(directory: str, recursive: bool = False) -> list[str]:
    """Find all supported image files in a directory."""
    pattern = "**/*" if recursive else "*"
    files = glob.glob(os.path.join(directory, pattern), recursive=recursive)
    return sorted(
        f for f in files
        if os.path.isfile(f) and os.path.splitext(f)[1].lower() in IMAGE_EXTENSIONS
    )


