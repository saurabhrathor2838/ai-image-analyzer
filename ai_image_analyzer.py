def test_metadata(pil_img: Image.Image, exif_dict: dict[int, Any]) -> TestResult:
    """
    Examine EXIF / XMP / IPTC metadata for AI-generation signatures.

    Recalibrated v2: Missing EXIF is **informative** but **not definitive** —
    many real screenshots and social-media images lack camera data.  Full
    camera EXIF is a strong real-photo signal.
    """
    findings: list[str] = []
    details: dict[str, Any] = {}
    ai_prob = 50.0   # neutral default
    confidence = 0.25  # metadata is a weak signal

    exif_human: dict[str, Any] = {}
    for tag_id, value in exif_dict.items():
        tag_name = ExifTags.TAGS.get(tag_id, f"tag_{tag_id}")
        exif_human[tag_name] = value
    details["exif"] = _json_safe(exif_human)

    # --- Software field ---
    software = exif_human.get("Software", "")
    details["software"] = str(software) if software else None

    if software:
        software_lower = str(software).lower()
        for kw in AI_KEYWORDS:
            if kw in software_lower:
                findings.append(f"AI keyword '{kw}' found in Software field: '{software}'")
                ai_prob = 95.0
                confidence = 0.95
                break
    else:
        details["no_software"] = True

    # --- Camera make / model ---
    camera_make = exif_human.get("Make", "")
    camera_model = exif_human.get("Model", "")
    details["camera_make"] = str(camera_make) if camera_make else None
    details["camera_model"] = str(camera_model) if camera_model else None

    has_timestamp = bool(exif_human.get("DateTimeOriginal")) or bool(exif_human.get("DateTime"))
    details["datetime_original"] = str(exif_human.get("DateTimeOriginal", "")) if exif_human.get("DateTimeOriginal") else None
    details["datetime"] = str(exif_human.get("DateTime", "")) if exif_human.get("DateTime") else None

    if not camera_model and not camera_make:
        findings.append("No camera make/model in EXIF (common for AI, screenshots, downloaded images)")
        ai_prob = min(95.0, ai_prob + 10.0)
        confidence = max(confidence, 0.25)
    else:
        combined_cam = f"{camera_make} {camera_model}".lower()
        for kw in AI_KEYWORDS:
            if kw in combined_cam:
                findings.append(f"AI keyword '{kw}' found in camera info")
                ai_prob = 90.0
                confidence = 0.9
                break
        else:
            findings.append("Camera make/model present in EXIF (consistent with a real photograph)")
            ai_prob = max(8.0, ai_prob - 25.0)
            confidence = max(confidence, 0.7)

    if has_timestamp:
        findings.append("Capture timestamp present (consistent with a real photograph)")
        ai_prob = max(5.0, ai_prob - 12.0)
        confidence = max(confidence, 0.5)
    else:
        findings.append("No capture timestamp in EXIF")
        ai_prob = min(95.0, ai_prob + 5.0)
        confidence = max(confidence, 0.25)

    # --- Resolution divisibility ---
    width, height = pil_img.size
    details["resolution"] = f"{width}x{height}"
    is_div_64 = (width % 64 == 0) and (height % 64 == 0)
    details["divisible_by_64"] = is_div_64

    if is_div_64:
        findings.append("Resolution divisible by 64 (common in diffusion model outputs)")
        ai_prob = min(95.0, ai_prob + 3.0)
        confidence = max(confidence, 0.3)

    explanation = "; ".join(findings) if findings else (
        "No metadata anomalies detected; camera EXIF present."
        if camera_model or camera_make else
        "No obvious AI metadata signatures detected."
    )

    return TestResult(
        name="Metadata Forensics",
        score=ai_prob,
        confidence=confidence,
        explanation=explanation,
        details=details,
    )


