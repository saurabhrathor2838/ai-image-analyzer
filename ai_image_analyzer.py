def _parse_jpeg_segments(raw_data: bytes) -> dict[str, bytes]:
    """Parse JPEG file segments and return a dict of segment marker → data."""
    segments: dict[str, bytes] = {}
    if len(raw_data) < 4 or raw_data[0] != 0xFF or raw_data[1] != 0xD8:
        return segments

    offset = 2  # skip SOI
    while offset < len(raw_data) - 1:
        if raw_data[offset] != 0xFF:
            offset += 1
            continue

        marker = raw_data[offset + 1]
        # SOI (0xD8), EOI (0xD9), RSTn (0xD0-0xD7) have no length field
        if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
            offset += 2
            continue

        if marker == 0xDA:  # SOS (Start of Scan) — image data follows
            break

        if offset + 4 > len(raw_data):
            break

        seg_len = struct.unpack(">H", raw_data[offset + 2:offset + 4])[0]
        if seg_len < 2 or offset + 2 + seg_len > len(raw_data):
            break

        seg_data = raw_data[offset + 4:offset + 2 + seg_len]

        marker_names = {
            0xE1: "APP1",   # EXIF / XMP
            0xE6: "APP6",
            0xED: "APP13",  # Photoshop IRB / Adobe
            0xEE: "APP14",  # Adobe
            0xFE: "COM",    # Comment
        }
        name = marker_names.get(marker, f"0x{marker:02X}")
        segments[name] = seg_data

        offset += 2 + seg_len

    return segments


def _parse_png_chunks(raw_data: bytes) -> dict[str, list[bytes]]:
    """Parse PNG file chunks and return a dict of chunk type → list of data."""
    chunks: dict[str, list[bytes]] = {}
    if len(raw_data) < 8 or raw_data[:8] != b"\x89PNG\r\n\x1a\n":
        return chunks

    offset = 8  # skip PNG signature
    while offset + 8 <= len(raw_data):
        try:
            length = struct.unpack(">I", raw_data[offset:offset + 4])[0]
        except struct.error:
            break
        if offset + 12 + length > len(raw_data):
            break

        chunk_type = raw_data[offset + 4:offset + 8].decode("ascii", errors="replace")
        chunk_data = raw_data[offset + 8:offset + 8 + length]

        chunks.setdefault(chunk_type, []).append(chunk_data)

        # CRC (4 bytes) — skip to next chunk
        offset += 12 + length

    return chunks


def _extract_xmp(raw_data: bytes) -> str:
    """Extract XMP metadata as a string from raw image bytes."""
    xmp_parts: list[str] = []

    # JPEG: look in APP1 segments for XMP namespace
    segments = _parse_jpeg_segments(raw_data)
    for seg_data in segments.values():
        if b"http://ns.adobe.com/xap/1.0/" in seg_data or b"<x:xmpmeta" in seg_data:
            try:
                # XMP data starts after the namespace URI
                ns_end = seg_data.find(b"http://ns.adobe.com/xap/1.0/")
                if ns_end >= 0:
                    xmp_start = ns_end + len(b"http://ns.adobe.com/xap/1.0/")
                    # Find the end of the XMP packet
                    xmp_end = seg_data.rfind(b"</x:xmpmeta>")
                    if xmp_end > xmp_start:
                        xmp_data = seg_data[xmp_start:xmp_end + len(b"</x:xmpmeta>")]
                        xmp_parts.append(xmp_data.decode("utf-8", errors="replace"))
            except Exception:
                pass

    # PNG: look in iTXt chunks for XMP
    chunks = _parse_png_chunks(raw_data)
    for chunk_data in chunks.get("iTXt", []):
        # iTXt format: keyword, compression_flag, compression_method,
        #                language_tag, translated_keyword, text
        try:
            keyword_end = chunk_data.find(b"\x00")
            if keyword_end == -1:
                continue
            keyword = chunk_data[:keyword_end].decode("utf-8", errors="replace")
            # Skip: compression_flag (1), compression_method (1), language_tag (null-terminated)
            remaining = chunk_data[keyword_end + 1:]
            if remaining and (keyword.lower().startswith("xml") or "xmp" in keyword.lower()):
                xmp_parts.append(remaining.decode("utf-8", errors="replace"))
        except Exception:
            pass

    # Also scan for raw XMP packets in the file
    for pattern in [b"<x:xmpmeta", b"<rdf:RDF"]:
        idx = raw_data.find(pattern)
        if idx >= 0:
            end_idx = raw_data.find(b">", idx)
            if end_idx > idx:
                # Try to extract a reasonable chunk of XMP
                xmp_text = raw_data[idx:end_idx + 5000].decode("utf-8", errors="replace")
                xmp_parts.append(xmp_text)

    return "\n".join(xmp_parts)


def _search_metadata_strings(raw_data: bytes, exif_dict: dict) -> list[str]:
    """Search raw file bytes and EXIF dict for AI-related strings."""
    found: list[str] = []
    raw_lower = raw_data.lower() if raw_data else b""

    for kw in C2PA_AI_KEYWORDS:
        kw_bytes = kw.encode("utf-8").lower()
        if kw_bytes in raw_lower:
            found.append(kw)
        # Also check EXIF dict values
        for val in exif_dict.values():
            if isinstance(val, bytes):
                if kw_bytes in val.lower():
                    if kw not in found:
                        found.append(kw)
            elif isinstance(val, str):
                if kw in val.lower():
                    if kw not in found:
                        found.append(kw)

    return found


def test_c2pa_exif(image_path: str, pil_img: Image.Image, exif_dict: dict[int, Any]) -> TestResult:
    """
    Enhanced C2PA and EXIF metadata verification.

    Uses raw byte parsing (fallback when exifread / pyc2pa are unavailable)
    to detect:

    • **C2PA ContentCredentials** manifests (embedded provenance)
    • **AI tool signatures** in EXIF, XMP, IPTC, and raw header data:
      DALL-E, Midjourney, Adobe Firefly, Stable Diffusion, etc.
    • **Adobe Photoshop IRB** data (APP13 segments)
    • **Missing provenance** — no camera EXIF, no timestamps, no provenance

    This test is definitive when it finds a direct AI signature (high
    confidence), and neutral when no signatures are found.
    """
    findings: list[str] = []
    details: dict[str, Any] = {}
    ai_prob = 50.0
    confidence = 0.3

    details["image_format"] = pil_img.format or "unknown"

    # Read raw bytes for deep metadata extraction
    raw_data: bytes = b""
    try:
        with open(image_path, "rb") as f:
            raw_data = f.read()
    except Exception:
        pass

    # --- C2PA ContentCredentials detection ---
    c2pa_markers = []
    c2pa_indicators = [
        b"contentcredentials", b"c2pa", b"content_credentials",
        b"contentauthenticity", b"cai_verify",
        b"http://c2pa.org", b"https://c2pa.org",
        b"adobe.contentauthenticity", b"manifest",
        b"stds:hash", b"adobe:signature",
    ]

    raw_lower = raw_data.lower() if raw_data else b""
    for indicator in c2pa_indicators:
        if indicator in raw_lower:
            c2pa_markers.append(indicator.decode("utf-8", errors="replace"))

    details["c2pa_markers"] = c2pa_markers

    if c2pa_markers:
        findings.append(f"C2PA / ContentCredentials metadata found: {', '.join(c2pa_markers)}")
        # C2PA presence alone is not an AI signal — it means provenance was
        # attached. But if combined with AI keywords, it's a strong signal.
        confidence = max(confidence, 0.4)

    # --- XMP extraction and analysis ---
    xmp_text = ""
    if raw_data:
        xmp_text = _extract_xmp(raw_data)

    details["xmp_found"] = bool(xmp_text)
    if xmp_text:
        xmp_lower = xmp_text.lower()
        details["xmp_length"] = len(xmp_text)

        # Check XMP for AI keywords
        xmp_ai_found = []
        for kw in C2PA_AI_KEYWORDS:
            if kw in xmp_lower:
                xmp_ai_found.append(kw)
        details["xmp_ai_keywords"] = xmp_ai_found

        if xmp_ai_found:
            findings.append(f"AI tool signatures found in XMP metadata: {', '.join(xmp_ai_found[:5])}")
            ai_prob = min(95.0, ai_prob + 30.0)
            confidence = max(confidence, 0.8)

        # Check XMP CreatorTool
        for marker in ["creatortool", "creator tool", "software", "author",
                        "artist", "credit", "source", "jobname"]:
            idx = xmp_lower.find(marker)
            if idx >= 0:
                # Extract surrounding text
                start = max(0, idx - 50)
                end = min(len(xmp_text), idx + 200)
                context = xmp_text[start:end].strip()
                context_lower = context.lower()
                for kw in C2PA_AI_KEYWORDS:
                    if kw in context_lower:
                        findings.append(f"AI-related text found in XMP field '{marker}': ...{context[:80]}...")
                        ai_prob = min(95.0, ai_prob + 20.0)
                        confidence = max(confidence, 0.7)
                        break
    else:
        details["xmp_found"] = False

    # --- Search raw bytes for AI keywords ---
    ai_keywords_found = []
    if raw_data:
        ai_keywords_found = _search_metadata_strings(raw_data, exif_dict)

    details["raw_ai_keywords"] = ai_keywords_found

    if ai_keywords_found:
        findings.append(
            f"AI-related strings found in raw metadata: {', '.join(ai_keywords_found[:5])}"
        )
        ai_prob = min(95.0, ai_prob + 25.0)
        confidence = max(confidence, 0.75)

    # --- Adobe Photoshop IRB / APP13 check ---
    adobe_segments = {k: v for k, v in _parse_jpeg_segments(raw_data).items() if k == "APP13"}
    if adobe_segments:
        details["photoshop_app13_found"] = True
        findings.append("Adobe Photoshop APP13 (IRB) segment detected — may contain provenance data")
        confidence = max(confidence, 0.5)
    else:
        details["photoshop_app13_found"] = False

    # --- EXIF completeness ---
    if exif_dict:
        exif_keys = list(exif_dict.keys())
        details["exif_tag_count"] = len(exif_keys)
        details["exif_tags"] = _json_safe({ExifTags.TAGS.get(k, f"tag_{k}"): str(v)[:100]
                                            for k, v in exif_dict.items()})

        # Check for comprehensive camera EXIF
        has_camera = bool(exif_dict.get(271)) or bool(exif_dict.get(272))  # Make, Model
        has_iso = bool(exif_dict.get(34855))    # ISOSpeedRatings
        has_focal = bool(exif_dict.get(37386))  # FocalLength
        has_exposure = bool(exif_dict.get(33437)) or bool(exif_dict.get(33434))  # FNumber, ExposureTime

        exif_completeness = sum([has_camera, has_iso, has_focal, has_exposure])
        details["exif_completeness"] = f"{exif_completeness}/4"

        if exif_completeness >= 3:
            findings.append(
                f"Rich camera EXIF present ({exif_completeness}/4 key fields: "
                f"make/model, ISO, focal length, exposure) — strong real-photo signal"
            )
            ai_prob = max(10.0, ai_prob - 30.0)
            confidence = max(confidence, 0.8)
        elif exif_completeness >= 1:
            findings.append(f"Partial EXIF present ({exif_completeness}/4 fields).")
            ai_prob = max(25.0, ai_prob - 10.0)
            confidence = max(confidence, 0.4)
    else:
        details["exif_tag_count"] = 0
        findings.append("No EXIF data found — no camera metadata present")
        # Metadata Forensics test already handles missing-EXIF as AI signal;
        # C2PA test stays neutral and focuses on provenance signatures.

    # --- Final verdict for this test ---
    explanation = "; ".join(findings) if findings else (
        "No C2PA or AI metadata signatures detected; EXIF provenance present.")

    return TestResult(
        name="C2PA Metadata Verification",
        score=ai_prob,
        confidence=confidence,
        explanation=explanation,
        details=details,
    )


# ════════════════════════════════════════════════════════════════════════════
#  Test 2 — Noise Pattern Analysis
# ════════════════════════════════════════════════════════════════════════════

def test_noise(cv_img: np.ndarray) -> TestResult:
    """
    Analyse noise patterns.

    Recalibrated v2:
      • Natural ISO noise **varies** spatially → strong REAL signal
      • Bayer CFA interpolation patterns → strong REAL signal
      • Uniform noise → AI signal (but weighted less)
    """
    findings: list[str] = []
    details: dict[str, Any] = {}
    ai_prob = 50.0
    confidence = 0.5

    gray = cv2.cvtColor(cv_img, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape

    # Guard against very small images
    if h < 64 or w < 64:
        return TestResult(
            name="Noise Pattern Analysis",
            score=50.0,
            confidence=0.2,
            explanation="Image too small for reliable noise analysis.",
            details={"noise_skip": "Image smaller than 64x64"},
        )

    # --- Regional noise variance ---
    block_size = 64
    noise_levels: list[float] = []

    for i in range(0, h - block_size + 1, block_size):
        for j in range(0, w - block_size + 1, block_size):
            block = gray[i:i + block_size, j:j + block_size].astype(np.float64)
            lap = cv2.Laplacian(block.astype(np.uint8), cv2.CV_64F)
            mad = np.median(np.abs(lap - np.median(lap)))
            sigma_est = mad * 1.4826
            noise_levels.append(sigma_est)

    noise_array = np.array(noise_levels)
    noise_cv = float(np.std(noise_array) / (np.mean(noise_array) + 1e-12))

    details["noise_regional_cv"] = round(noise_cv, 4)
    details["noise_regional_std"] = round(float(np.std(noise_array)), 4)
    details["noise_regional_mean"] = round(float(np.mean(noise_array)), 4)

    if noise_cv > 0.20:
        findings.append(
            f"Noise varies naturally across regions (CV={noise_cv:.3f}). "
            f"Consistent with real camera sensor noise."
        )
        ai_prob = max(10.0, ai_prob - 28.0)
        confidence = max(confidence, 0.7)
    elif noise_cv > 0.08:
        findings.append(f"Noise variation is moderate (CV={noise_cv:.3f}).")
        ai_prob = min(95.0, ai_prob + 5.0)
        confidence = max(confidence, 0.4)
    else:
        findings.append(
            f"Noise is unusually uniform (CV={noise_cv:.3f}). "
            f"Real photos typically show spatial noise variation."
        )
        ai_prob = min(95.0, ai_prob + 22.0)
        confidence = max(confidence, 0.7)

    # --- Chroma noise ---
    b, g, r = cv2.split(cv_img)
    chroma_noise_b = float(np.std(b.astype(np.float64) - g.astype(np.float64)))
    chroma_noise_r = float(np.std(r.astype(np.float64) - g.astype(np.float64)))
    avg_chroma_noise = (chroma_noise_b + chroma_noise_r) / 2.0
    details["chroma_noise"] = round(avg_chroma_noise, 4)

    if avg_chroma_noise > 3.0:
        findings.append(f"Chroma noise present ({avg_chroma_noise:.2f}).")
        # Only count as real signal if CFA patterns are also detected
        cfa_pre = _check_cfa_artifacts(gray, b, g, r)
        if cfa_pre > 0.10:
            findings.append("Combined with CFA detection — consistent with real sensor chroma noise.")
            ai_prob = max(15.0, ai_prob - 12.0)
            confidence = max(confidence, 0.6)
        else:
            findings.append("But no CFA patterns — chroma noise may be from synthesis, not sensor.")
            confidence = max(confidence, 0.3)
    elif avg_chroma_noise < 1.0:
        findings.append(f"Very low chroma noise ({avg_chroma_noise:.2f}) — AI images can lack sensor chroma noise.")
        ai_prob = min(80.0, ai_prob + 12.0)
        confidence = max(confidence, 0.5)

    # --- CFA (Bayer) pattern detection ---
    cfa_score = _check_cfa_artifacts(gray, b, g, r)
    details["cfa_detection_score"] = round(cfa_score, 4)

    if cfa_score > 0.10:
        findings.append(
            f"CFA/Bayer interpolation patterns detected (score={cfa_score:.3f}). "
            f"Strong indicator of a real digital camera sensor."
        )
        ai_prob = max(5.0, ai_prob - 25.0)
        confidence = max(confidence, 0.8)
    else:
        findings.append("No CFA interpolation patterns detected — consistent with direct RGB synthesis.")
        ai_prob = min(95.0, ai_prob + 8.0)
        confidence = max(confidence, 0.5)

    explanation = "; ".join(findings)
    return TestResult(
        name="Noise Pattern Analysis",
        score=ai_prob,
        confidence=confidence,
        explanation=explanation,
        details=details,
    )


def _check_cfa_artifacts(gray: np.ndarray, b: np.ndarray, g: np.ndarray, r: np.ndarray) -> float:
    """Check for Colour Filter Array (CFA) interpolation artifacts.

    Only samples from **non-uniform** regions to avoid false positives on
    images with large flat areas (e.g. notebook pages, white backgrounds).

    Additionally applies a background-smoothness gate: if the background
    is hyper-smooth (std < 5) but the cross-channel HF correlation is
    very high (> 0.50), the correlation is likely from synthetic content
    rather than genuine Bayer interpolation — the score is dampened.
    """
    try:
        h, w = gray.shape
        if h < 40 or w < 40:
            return 0.0

        # ── Background smoothness check (for false-positive suppression) ──
        lap = cv2.Laplacian(gray, cv2.CV_64F)
        active_mask = np.abs(lap) > 1.0  # pixels with real detail
        smooth_fraction = float((h * w - active_mask.sum()) / (h * w))
        if active_mask.sum() < 100:
            return 0.0  # too uniform — can't assess CFA

        b_hf = b.astype(np.float64) - cv2.GaussianBlur(b.astype(np.float64), (0, 0), 1)
        g_hf = g.astype(np.float64) - cv2.GaussianBlur(g.astype(np.float64), (0, 0), 1)
        r_hf = r.astype(np.float64) - cv2.GaussianBlur(r.astype(np.float64), (0, 0), 1)

        # Flatten and filter to active pixels only
        b_flat = b_hf[active_mask]
        g_flat = g_hf[active_mask]
        r_flat = r_hf[active_mask]

        bg_corr = np.corrcoef(b_flat, g_flat)[0, 1]
        gr_corr = np.corrcoef(g_flat, r_flat)[0, 1]
        br_corr = np.corrcoef(b_flat, r_flat)[0, 1]

        if any(np.isnan(c) for c in [bg_corr, gr_corr, br_corr]):
            return 0.0

        avg_correlation = (abs(bg_corr) + abs(gr_corr) + abs(br_corr)) / 3.0

        # ── False-positive suppression ────────────────────────────────
        # Extremely high cross-channel HF correlation (> 0.50) combined
        # with a large smooth background is characteristic of AI generation,
        # not genuine Bayer CFA interpolation.  Real camera photos have
        # textured backgrounds (paper grain, sensor noise) that keep the
        # smooth pixel fraction low (< 10%) even when CFA is present.
        if avg_correlation > 0.50 and smooth_fraction > 0.10:
            return 0.0  # Suppress — likely synthetic correlation

        return float(avg_correlation)
    except Exception:
        return 0.0


# ════════════════════════════════════════════════════════════════════════════
#  Text & Grid Anomaly Detector (helper)
# ════════════════════════════════════════════════════════════════════════════

def _detect_text_grid_anomalies(cv_img: np.ndarray) -> tuple[float, dict[str, Any]]:
    """
    Detect AI-generated text / diagram anomalies.

    Works with **any** background colour (white, coloured, or gradient).
    AI-generated notebook pages, diagrams, and text images lack the
    subtle imperfections of real photographs:
    - Hyper-smooth backgrounds (no paper texture, no sensor noise)
    - Synthetic ink strokes (uniform colour, no natural pen variation)
    - Perfectly periodic grid / text-line patterns
    - Overly regular edge spacing / dense edge rows

    Returns ``(anomaly_score, details)`` where *anomaly_score* is 0-50
    (added to the Visual test's AI probability).
    """
    gray = cv2.cvtColor(cv_img, cv2.COLOR_BGR2GRAY)
    h, w = gray.shape
    if h < 64 or w < 64:
        return 0.0, {"anomaly_skip": "Image too small"}

    b, g, r = cv2.split(cv_img)
    details: dict[str, Any] = {}
    score = 0.0

    # -- 1. Local variance (smoothness) -- catches gradient backgrounds --
    # Laplacian misses gradient backgrounds (low Laplacian but high std).
    # Local variance within a 9x9 window correctly identifies uniform areas.
    local_mean = cv2.boxFilter(gray.astype(np.float64), -1, (9, 9))
    local_sqmean = cv2.boxFilter(gray.astype(np.float64) ** 2, -1, (9, 9))
    local_var = np.maximum(0, local_sqmean - local_mean ** 2)
    local_std = np.sqrt(local_var)

    uniform_mask = (local_var < 16.0).astype(np.uint8)  # std < 4
    uniform_fraction = float(uniform_mask.sum()) / (h * w)
    details["uniform_pixel_coverage"] = round(uniform_fraction, 4)

    if uniform_fraction > 0.70:
        details["large_uniform_background"] = True
        score += 25.0
    elif uniform_fraction > 0.40:
        details["moderate_uniform_background"] = True
        score += 15.0
    elif uniform_fraction > 0.15:
        score += 5.0

    # -- 2. Background texture smoothness (no paper grain / sensor noise) --
    if uniform_mask.sum() > 200:
        avg_local_std = float(np.mean(local_std[uniform_mask > 0]))
        details["avg_local_std"] = round(avg_local_std, 4)

        if avg_local_std < 1.5:
            details["hyper_smooth_background"] = True
            score += 25.0
        elif avg_local_std < 3.0:
            details["smooth_background"] = True
            score += 10.0

    # -- 3. Periodic grid / text-line patterns via FFT --
    gray_f = gray.astype(np.float64) - np.mean(gray)
    fft = np.fft.fft2(gray_f)
    magnitude = np.log1p(np.abs(np.fft.fftshift(fft)))
    center_h, center_w = h // 2, w // 2

    h_profile = magnitude[center_h, :].copy()
    v_profile = magnitude[:, center_w].copy()

    hw = min(w // 12, 40)
    h_profile[max(0, center_w - hw):center_w + hw] = 0
    hh = min(h // 12, 40)
    v_profile[max(0, center_h - hh):center_h + hh] = 0

    h_threshold = np.mean(h_profile) + 2.0 * np.std(h_profile)
    v_threshold = np.mean(v_profile) + 2.0 * np.std(v_profile)
    h_peaks = int(np.sum(h_profile > h_threshold))
    v_peaks = int(np.sum(v_profile > v_threshold))
    details["horizontal_freq_peaks"] = h_peaks
    details["vertical_freq_peaks"] = v_peaks

    if h_peaks >= 3 or v_peaks >= 3:
        details["periodic_grid_pattern"] = True
        score += 20.0
    elif h_peaks >= 1 or v_peaks >= 1:
        score += 5.0

    # -- 4. Edge-row density & regularity (text / diagram patterns) --
    edges = cv2.Canny(gray, 50, 150)

    edge_rows = np.sum(edges > 0, axis=1)
    edge_row_indices = np.where(edge_rows > 0)[0]
    if len(edge_row_indices) > 5:
        gaps = np.diff(edge_row_indices).astype(float)
        gap_mean = float(np.mean(gaps))
        gap_std = float(np.std(gaps))
        edge_row_density = len(edge_row_indices) / h
        details["edge_row_density"] = round(edge_row_density, 4)

        if edge_row_density > 0.95 and gap_mean < 3 and uniform_fraction > 0.15:
            details["dense_edge_rows"] = True
            details["gap_mean"] = round(gap_mean, 4)
            score += 20.0
        elif gap_mean > 5:
            regularity = 1.0 - min(1.0, gap_std / (gap_mean + 1e-8))
            details["edge_row_regularity"] = round(regularity, 4)
            if regularity > 0.85:
                details["regular_edge_spacing"] = True
                score += 15.0

    # -- 5. Color uniformity of ink regions (synthetic strokes) --
    dark_pixels = gray < 100
    if dark_pixels.sum() > 500:
        dark_b = b[dark_pixels]
        dark_g = g[dark_pixels]
        dark_r = r[dark_pixels]
        ink_color_std = float(np.mean([
            np.std(dark_b.astype(np.float64)),
            np.std(dark_g.astype(np.float64)),
            np.std(dark_r.astype(np.float64)),
        ]))
        details["ink_color_std"] = round(ink_color_std, 4)

        if ink_color_std < 15.0 and uniform_fraction > 0.15:
            details["uniform_ink_color"] = True
            score += 10.0

    details["total_anomaly_score"] = round(score, 2)
    return min(50.0, score), details



